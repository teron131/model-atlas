/** Rate every task benchmark's profile against each benchmark domain with a decision model, then write the domain shares module that `domains.ts` serves. Each domain is one 0–4 score question, and its expected level, squared, is its weight once it reaches the floor, so major domains outweigh a spread of minor ones; the kept weights are shared out to integers summing to 100. Requests go through TypeSafe's SDK to any System One host: DECISION_API_KEY is required, and DECISION_BASE_URL and DECISION_MODEL default to Vercel AI Gateway and Decider v1.3. */

import { writeFile } from "node:fs/promises";

import { score, TypeSafeClient } from "@typesafe-ai/sdk";
import PQueue from "p-queue";

import {
  BENCHMARK_DOMAINS,
  BENCHMARK_LABELS,
  BENCHMARK_PROFILES,
  type TaskBenchmarkKey,
} from "../src/model-atlas/benchmarks/catalog";

// The SDK appends /v1/systemone to this root.
const DEFAULT_BASE_URL = "https://ai-gateway.vercel.sh/typesafe";
const DEFAULT_MODEL = "perplexity/pplx-decider-v1.3";
const GENERATED_PATH = "src/model-atlas/benchmarks/catalog/domain-shares.generated.ts";
const RUBRIC = [
  "0: irrelevant; this ability barely affects whether a model scores well",
  "1: minor; it appears in the tasks but rarely separates strong from weak models",
  "2: moderate; it is one of several abilities that decide the score",
  "3: major; it is one of the main abilities that decide the score",
  "4: dominant; the score is mainly a measure of this ability",
] as const;
// Halfway between the rubric's "minor" and "moderate": a domain rated below it gets no share.
const FLOOR = 1.5;
const PROFILE_ROWS = [
  ["Given", "given"],
  ["Produces", "produces"],
  ["Task mix", "taskMix"],
  ["Environment", "environment"],
  ["Graded by", "gradedBy"],
] as const;

// From the shell, not `.env`, which `pnpm env:sync` mirrors into the Vercel deployments that never call a decision model.
const apiKey = process.env.DECISION_API_KEY;
if (!apiKey) {
  throw new Error(
    "Set DECISION_API_KEY to a Vercel AI Gateway key, or to another System One host's key with DECISION_BASE_URL",
  );
}
const model = process.env.DECISION_MODEL || DEFAULT_MODEL;
const client = new TypeSafeClient({
  apiKey,
  baseURL: process.env.DECISION_BASE_URL || DEFAULT_BASE_URL,
  defaultModel: model,
  // Overloaded hosts answer 503 "try again shortly".
  retry: { maxRetries: 4 },
  // OpenRouter does not document accepting the zstd request bodies the SDK sends by default.
  compression: false,
});
const questions = Object.fromEntries(
  BENCHMARK_DOMAINS.map(({ key, name, definition }) => [
    key,
    score(
      `How much does ${name} (${definition}) decide a model's score on this benchmark? Judge what separates high and low scorers, not what merely appears in the tasks or is needed by every benchmark; most benchmarks are decided by one to three abilities, so rate the rest 0 or 1.`,
      RUBRIC,
    ),
  ]),
);
const queue = new PQueue({ concurrency: 6 });
const results = await Promise.all(
  (Object.keys(BENCHMARK_PROFILES) as TaskBenchmarkKey[]).map((key) => queue.add(() => rate(key))),
);

await writeFile(
  GENERATED_PATH,
  [
    `// Generated by \`pnpm domains:label\` from each task benchmark's profile and the domain definitions, rated by ${model}; do not edit directly.`,
    "",
    'import type { DomainShares } from "./domains";',
    'import type { TaskBenchmarkKey } from "./portfolio";',
    "",
    "export const BENCHMARK_DOMAIN_SHARES = {",
    ...results.map(
      ({ key, shares }) =>
        `  ${key}: { ${shares.map(([domain, share]) => `${domain}: ${share}`).join(", ")} },`,
    ),
    "} satisfies Record<TaskBenchmarkKey, DomainShares>;",
    "",
  ].join("\n"),
);
console.log(`wrote ${GENERATED_PATH}`);

/** One benchmark's shares, largest first; empty when no domain reaches the floor. */
async function rate(key: TaskBenchmarkKey) {
  const profile = BENCHMARK_PROFILES[key];
  const { answers } = await client.systemOne({
    state: [
      `Benchmark: ${BENCHMARK_LABELS[key]}`,
      ...PROFILE_ROWS.map(([row, field]) => `${row}: ${profile[field]}`),
      "",
      "The abilities being rated, one question each:",
      ...BENCHMARK_DOMAINS.map((domain) => `- ${domain.name}: ${domain.definition}`),
    ].join("\n"),
    questions,
  });
  const weights = Object.entries(answers)
    .filter(([, answer]) => answer.score >= FLOOR)
    .sort(([, a], [, b]) => b.score - a.score)
    .map(([domain, answer]) => [domain, answer.score ** 2] as const);
  const total = weights.reduce((sum, [, weight]) => sum + weight, 0);
  const rounded = weights.map(
    ([domain, weight]) => [domain, Math.round((100 * weight) / total)] as const,
  );
  // Rounding can miss 100 by a point or two; the largest share absorbs it.
  const drift = 100 - rounded.reduce((sum, [, share]) => sum + share, 0);
  const shares = rounded.map(
    ([domain, share], index) => [domain, index === 0 ? share + drift : share] as const,
  );
  return { key, shares };
}
